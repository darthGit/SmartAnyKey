// Initial installation setup: generates both `.env` files with their own
// secrets, so an install does not go to production on the publicly known demo
// keys from `docker/.env.example`.
//
//   node scripts/bootstrap.mjs [--force] [--from-installer]
//   docker compose run --rm app node scripts/bootstrap.mjs
//
// Why a separate step instead of "copy .env.example": the example holds the
// **real public** Supabase demo JWTs (`iss: supabase-demo`) and placeholder
// passwords. A copied example is a working install, so that path becomes the
// default unless this one is made more convenient than copying.
//
// ANON/SERVICE_ROLE are signed with a generated `JWT_SECRET` via `node:crypto`
// (HMAC-SHA256, ~10 lines, zero dependencies). We do not write our own crypto;
// stdlib HMAC is not "own crypto" but a call into a vetted implementation.
//
// ⚠ Without `--force` it NEVER overwrites an existing file. Losing
// `NUXT_CRED_ENCRYPTION_KEY` = losing all stored passwords (ADR-009): the data
// remains, nothing can decrypt it. Hence the default is "don't touch".
import { createHmac, randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const YEAR = 60 * 60 * 24 * 365

function b64url(input) {
  return Buffer.from(input).toString('base64')
    .replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}

/** HS256 JWT. The same format kong/GoTrue/PostgREST expect from Supabase keys. */
export function signHs256(payload, secret, { iat = 1700000000, expSeconds = 10 * YEAR } = {}) {
  const head = b64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }))
  const body = b64url(JSON.stringify({ iss: 'supabase', iat, exp: iat + expSeconds, ...payload }))
  const sig = createHmac('sha256', secret).update(`${head}.${body}`).digest('base64')
    .replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
  return `${head}.${body}.${sig}`
}

/**
 * All installation secrets in one go. Reads and writes nothing — testable
 * without a filesystem.
 */
export function generateSecrets() {
  // ≥32 characters: GoTrue refuses to work with a shorter JWT_SECRET.
  const jwtSecret = randomBytes(32).toString('hex')
  return {
    postgresPassword: randomBytes(24).toString('hex'),
    jwtSecret,
    anonKey: signHs256({ role: 'anon' }, jwtSecret),
    serviceKey: signHs256({ role: 'service_role' }, jwtSecret),
    // ADR-009: exactly 32 bytes = 64 hex.
    credEncryptionKey: randomBytes(32).toString('hex'),
    executorSecret: randomBytes(16).toString('hex'),
    secretKeyBase: randomBytes(48).toString('base64'),
    // Upstream ships these with example values every install would share; the S3
    // pair opens Storage on the public port without an apikey. Hex keeps .env safe.
    realtimeDbEncKey: randomBytes(8).toString('hex'), // exactly 16 characters
    pgMetaCryptoKey: randomBytes(16).toString('hex'),
    s3AccessKeyId: randomBytes(16).toString('hex'),
    s3AccessKeySecret: randomBytes(32).toString('hex'),
  }
}

/**
 * Write with a guard. Returns 'written' | 'kept' — a string, not a boolean,
 * so the call reads as a fact rather than "true of something".
 */
export function writeEnvFile(path, content, { force = false } = {}) {
  if (existsSync(path) && !force)
    return 'kept'
  writeFileSync(path, content)
  return 'written'
}

export function dockerEnv(s, existing = {}) {
  // Take the example as a template and replace only the secrets — the rest
  // (ports, limits, GoTrue flags) are upstream-maintained defaults we keep.
  const template = readFileSync('docker/.env.example', 'utf8')
  const values = {
    POSTGRES_PASSWORD: s.postgresPassword,
    JWT_SECRET: s.jwtSecret,
    ANON_KEY: s.anonKey,
    SERVICE_ROLE_KEY: s.serviceKey,
    SECRET_KEY_BASE: s.secretKeyBase,
    REALTIME_DB_ENC_KEY: s.realtimeDbEncKey,
    PG_META_CRYPTO_KEY: s.pgMetaCryptoKey,
    S3_PROTOCOL_ACCESS_KEY_ID: s.s3AccessKeyId,
    S3_PROTOCOL_ACCESS_KEY_SECRET: s.s3AccessKeySecret,
    EXECUTOR_SHARED_SECRET: s.executorSecret,
    // The same key as in the root `.env`: the `app` container must read the same
    // `password_enc` as host-dev.
    NUXT_CRED_ENCRYPTION_KEY: s.credEncryptionKey,
    ...existing,
  }
  const seen = new Set()
  const out = template.split('\n').map((line) => {
    const m = /^([A-Z0-9_]+)=/.exec(line)
    if (!m || !(m[1] in values))
      return line
    seen.add(m[1])
    return `${m[1]}=${values[m[1]]}`
  })
  for (const [k, v] of Object.entries(values)) {
    if (!seen.has(k))
      out.push(`${k}=${v}`)
  }
  return `${out.join('\n').trimEnd()}\n`
}

function rootEnv(s) {
  return `# Generated by scripts/bootstrap.mjs — secrets are YOUR OWN, not demo.
# The public Supabase address must be reachable BOTH from the browser AND from
# the app container (the module's server client uses the PUBLIC address) →
# use the machine's IP/DNS, NOT localhost, if the app runs in compose.
SUPABASE_URL=http://localhost:8000
SUPABASE_KEY=${s.anonKey}
SUPABASE_SERVICE_KEY=${s.serviceKey}

# ADR-009: 64 hex. Losing it = losing all stored passwords. Back it up SEPARATELY.
NUXT_CRED_ENCRYPTION_KEY=${s.credEncryptionKey}

# ADR-016: shared secret for the executor service (must match docker/.env).
NUXT_EXECUTOR_SECRET=${s.executorSecret}

# ADR-018: task runtime registry. Path is /run-task, NOT the legacy /run.
# Empty = tasks cannot be created (shown on screen, not a "button does nothing").
NUXT_TASK_RUNNERS={"python312":"http://127.0.0.1:8090/run-task","node22":"http://127.0.0.1:8090/run-task","bash":"http://127.0.0.1:8090/run-task"}

# First admin (CHANGE THIS, then: node scripts/seed-admin.mjs)
RBAC_ADMIN_EMAIL=
RBAC_ADMIN_PASSWORD=

# How many trailing phone digits count as a match (e.g. 9 for a Ukrainian number). Empty = exact match.
NUXT_PUBLIC_PHONE_MATCH_TAIL=

# External app address — only for links a person reads outside the browser.
NUXT_PUBLIC_APP_URL=
`
}

/** Public demo values from the example — none may end up in a generated file. */
const ALWAYS_SECRET = ['POSTGRES_PASSWORD', 'JWT_SECRET', 'ANON_KEY', 'SERVICE_ROLE_KEY',
  'EXECUTOR_SHARED_SECRET']

/** Secret keys of the template with their example values: the fixed list plus
 *  every key the upstream comment asks to "generate with …" — so a secret added
 *  upstream is covered without editing this file. */
function exampleSecrets(exampleText) {
  const lines = exampleText.split('\n')
  const out = new Map()
  lines.forEach((line, i) => {
    const m = /^([A-Z0-9_]+)=(.+)$/.exec(line.trim())
    if (m && (ALWAYS_SECRET.includes(m[1]) || /generate with/i.test(lines.slice(Math.max(0, i - 3), i).join(' '))))
      out.set(m[1], m[2].trim())
  })
  return out
}

export function demoValues(exampleText) {
  return new Set(exampleSecrets(exampleText).values())
}

/** Keys of an existing env file that still hold the template's example secret. */
export function staleSecrets(envText, exampleText) {
  const current = new Map(envText.split('\n').map(l => [l.split('=')[0], l.slice(l.indexOf('=') + 1).trim()]))
  return [...exampleSecrets(exampleText)].filter(([k, v]) => current.get(k) === v).map(([k]) => k)
}

function main(argv) {
  const force = argv.includes('--force')
  const unknown = argv.filter(a => a.startsWith('--') && !['--force', '--from-installer'].includes(a))
  if (unknown.length)
    throw new Error(`unknown flag: ${unknown.join(', ')}`)

  const s = generateSecrets()
  const demo = demoValues(readFileSync('docker/.env.example', 'utf8'))
  for (const [name, value] of Object.entries(s)) {
    if (demo.has(value))
      throw new Error(`generated ${name} equals a demo value — this should not be possible`)
  }

  const results = {
    'docker/.env': writeEnvFile('docker/.env', dockerEnv(s), { force }),
    '.env': writeEnvFile('.env', rootEnv(s), { force }),
  }

  for (const [path, r] of Object.entries(results)) {
    console.log(r === 'written' ? `✓ ${path} generated` : `• ${path} LEFT ALONE (already exists)`)
  }

  if (results['docker/.env'] === 'kept') {
    const stale = staleSecrets(readFileSync('docker/.env', 'utf8'), readFileSync('docker/.env.example', 'utf8'))
    if (stale.length) {
      console.log(`\n⚠ docker/.env still uses the public example value for: ${stale.join(', ')}.`)
      console.log('  Every install shipped with these values shares them. Put fresh ones in (format: the comment')
      console.log('  above each key in docker/.env.example) and recreate the services that read them.')
      console.log('  Keep NUXT_CRED_ENCRYPTION_KEY as it is.')
    }
  }
  if (Object.values(results).includes('kept')) {
    console.log('\nExisting files were not overwritten. On purpose: they may hold')
    console.log('NUXT_CRED_ENCRYPTION_KEY, without which all stored passwords are dead.')
    console.log('To really regenerate, use `--force` after saving the old key.')
  }
  for (const line of nextSteps({ written: Object.values(results).includes('written'), fromInstaller: argv.includes('--from-installer') }))
    console.log(line)
}

/** The manual path, printed only when someone runs this by hand: install.sh does all of it. */
export function nextSteps({ written, fromInstaller }) {
  if (!written || fromInstaller)
    return []
  return [
    '\nNext:',
    '  1. docker compose -f docker/docker-compose.yml --env-file docker/.env up -d',
    '  2. docker compose … run --rm app node scripts/db-migrate.mjs',
    '  3. set RBAC_ADMIN_EMAIL/RBAC_ADMIN_PASSWORD in .env, then',
    '     docker compose … run --rm app node scripts/seed-admin.mjs',
    '\n⚠ If the app runs in compose, set SAK_PUBLIC_SUPABASE_URL',
    '  to the machine IP/DNS: the server Supabase client uses the PUBLIC address,',
    '  so with `localhost` every gated route returns 500.',
  ]
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main(process.argv.slice(2))
  }
  catch (e) {
    console.error(`bootstrap: ${e.message}`)
    process.exit(1)
  }
}
